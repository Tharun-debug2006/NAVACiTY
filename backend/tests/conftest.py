"""Shared pytest fixtures for the NavaCity backend tests.

The tests run against a *temporary* SQLite database that is seeded from the
generated CSV dataset, so they never touch ``data/navacity.db``.
"""

from __future__ import annotations

import os
import shutil
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import pytest  # noqa: E402

# Point the application at a throw-away database BEFORE the app modules are
# imported, because the engine is created at import time.
_TMP_DIR = tempfile.mkdtemp(prefix="navacity_test_")
os.environ["NAVACITY_DB_PATH"] = str(Path(_TMP_DIR) / "test_navacity.db")

# The authority area is protected by the backend.  The tests run in the
# "local" environment, where the demo password "dumpme" is accepted, and they
# exercise the protection explicitly (see tests/test_auth.py).
os.environ.setdefault("NAVACITY_ENV", "local")
os.environ.setdefault("NAVACITY_AUTH_PASSWORD", "dumpme")

from fastapi.testclient import TestClient  # noqa: E402

from backend.app.auth import auth_service  # noqa: E402
from backend.app.database import Base, DemandRecord, engine  # noqa: E402
from backend.app.main import app  # noqa: E402
from backend.app.services.model_service import model_service  # noqa: E402
from backend.seed_database import seed_network, seed_records  # noqa: E402
from backend.app.config import settings  # noqa: E402


@pytest.fixture(scope="session")
def seeded_database() -> str:
    """Create and seed the temporary test database.  Returns the db path.

    The full generated dataset (95 000 rows) is inserted with a single bulk
    insert, so the whole fixture stays well under a minute.
    """
    Base.metadata.drop_all(bind=engine)
    Base.metadata.create_all(bind=engine)

    from backend.app.database import SessionLocal

    session = SessionLocal()
    try:
        seed_network(session)
        session.commit()
        if settings.dataset_csv.exists():
            seed_records(session, settings.dataset_csv)
            session.commit()
        else:  # pragma: no cover - the dataset is generated by the README steps
            raise RuntimeError(
                f"Dataset not found at {settings.dataset_csv}. "
                "Run 'python ml\\generate_dataset.py' first."
            )
    finally:
        session.close()
    return str(settings.db_path)


@pytest.fixture(scope="session")
def client(seeded_database: str) -> TestClient:
    """A FastAPI test client with the model bundle loaded."""
    model_service.load()
    with TestClient(app) as test_client:
        yield test_client


@pytest.fixture(scope="function")
def authority_token(client) -> str:
    """A valid authority session token for the protected endpoints.

    The fixture is deliberately **function scoped**: some tests re-configure the
    authentication service (for example to check that the production mode
    refuses the demo password), and that revokes every live session.  A
    session-scoped token would then be rejected by the following tests.
    """
    response = client.post("/api/auth/login", json={"password": "dumpme"})
    assert response.status_code == 200, response.text
    return response.json()["access_token"]


@pytest.fixture(scope="function")
def authority_headers(authority_token: str) -> dict:
    """The Authorization header of a signed-in authority operator."""
    return {"Authorization": f"Bearer {authority_token}"}


@pytest.fixture(scope="session")
def sample_rows() -> int:
    """The number of records that were seeded into the test database."""
    from backend.app.database import SessionLocal
    from sqlalchemy import func, select

    session = SessionLocal()
    try:
        return int(session.scalar(select(func.count()).select_from(DemandRecord)) or 0)
    finally:
        session.close()
