"""Generate the SIMULATED NavaCity transit dataset.

Usage (from the repository root, Windows PowerShell)::

    python ml\\generate_dataset.py

The script is fully deterministic: the same seed always produces exactly the
same CSV file.  It writes

* ``data/generated/navacity_transport.csv``  - the hourly demand dataset
* ``data/generated/navacity_network.json``   - the static network description

and prints a quality report (row counts, distributions, peak hours) so the
generated data can be inspected without opening the CSV.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import pandas as pd  # noqa: E402

from navacity_core.config import (  # noqa: E402
    DATASET_CSV,
    GENERATED_DIR,
    NETWORK_JSON,
    RANDOM_SEED,
    SIM_END_DATE,
    SIM_START_DATE,
)
from navacity_core.network import build_network  # noqa: E402
from navacity_core.simulator import generate_dataset  # noqa: E402

DATA_NOTICE = (
    "SIMULATED DATA - NavaCity is a fictional city generated by "
    "navacity_core.simulator. It does not describe any real city, operator "
    "or passenger survey."
)


def print_report(df: pd.DataFrame) -> None:
    """Print a short quality report of the generated dataset."""
    print("=" * 72)
    print("NavaCity SIMULATED dataset report")
    print("=" * 72)
    print(f"Rows                 : {len(df):,}")
    print(f"Columns              : {len(df.columns)}")
    print(f"Date range           : {df['date'].min()} -> {df['date'].max()}")
    print(f"Distinct dates       : {df['date'].nunique()}")
    print(f"Metro rows           : {(df['mode'] == 'metro').sum():,}")
    print(f"Bus rows             : {(df['mode'] == 'bus').sum():,}")
    print(f"Routes               : {df['route_id'].nunique()}")
    print(f"Stations / stops     : {pd.concat([df['origin_id'], df['dest_id']]).nunique()}")
    print(f"Total passengers     : {int(df['passenger_count'].sum()):,}")
    print(f"Missing values       : {int(df.isna().sum().sum())}")
    print()

    print("-- Crowd level distribution --")
    crowd = df["crowd_level"].value_counts().reindex(
        ["Low", "Moderate", "High", "Critical"], fill_value=0
    )
    for level, count in crowd.items():
        share = 100.0 * count / len(df)
        print(f"  {level:<9} {count:>9,}  {share:5.1f}%")
    print(f"  Overcrowded rows (occupancy >= 80%): {int(df['is_overcrowded'].sum()):,}")
    print()

    print("-- Average demand by hour (weekday rows only) --")
    weekday = df[(~df["is_weekend"]) & (~df["is_holiday"])]
    by_hour = weekday.groupby("hour")["passenger_count"].mean().round(1)
    for hour, value in by_hour.items():
        bar = "#" * int(min(60, value / max(by_hour.max(), 1) * 60))
        print(f"  {hour:02d}:00  {value:>8.1f}  {bar}")
    print()

    print("-- Mode comparison (mean passengers per route-segment-hour) --")
    print(df.groupby("mode")["passenger_count"].mean().round(1).to_string())
    print()

    print("-- Top 5 busiest route segments (mean passengers) --")
    top = (
        df.groupby(["route_id", "route_name", "origin_name", "dest_name"])["passenger_count"]
        .mean()
        .sort_values(ascending=False)
        .head(5)
    )
    for key, value in top.items():
        print(f"  {key[0]} {key[2]} -> {key[3]}: {value:,.1f}")
    print()

    print("-- Special event impact (mean occupancy %, event vs normal) --")
    ev = df[df["special_event"]]["occupancy_pct"].mean()
    non_ev = df[~df["special_event"]]["occupancy_pct"].mean()
    print(f"  event rows   : {ev:.2f}%  (n={int(df['special_event'].sum()):,})")
    print(f"  normal rows  : {non_ev:.2f}%  (n={int((~df['special_event']).sum()):,})")
    print()
    print(DATA_NOTICE)
    print("=" * 72)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the NavaCity dataset")
    parser.add_argument("--start", default=SIM_START_DATE.isoformat())
    parser.add_argument("--end", default=SIM_END_DATE.isoformat())
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    parser.add_argument(
        "--samples-per-day",
        type=int,
        default=4,
        help="hourly observations generated per route-segment and day",
    )
    parser.add_argument(
        "--no-report", action="store_true", help="skip the quality report"
    )
    args = parser.parse_args()

    start_date = pd.Timestamp(args.start).date()
    end_date = pd.Timestamp(args.end).date()
    if end_date < start_date:
        print("ERROR: --end must not be earlier than --start", file=sys.stderr)
        return 2

    print(f"Generating SIMULATED NavaCity data {start_date} -> {end_date} "
          f"(seed={args.seed}) ...")
    df = generate_dataset(
        start_date=start_date,
        end_date=end_date,
        seed=args.seed,
        samples_per_day=args.samples_per_day,
    )

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(DATASET_CSV, index=False)
    print(f"Dataset written to {DATASET_CSV}")

    network = build_network()
    network["data_notice"] = DATA_NOTICE
    network["generated_at"] = pd.Timestamp.now(tz="UTC").isoformat()
    with open(NETWORK_JSON, "w", encoding="utf-8") as fh:
        json.dump(network, fh, indent=2)
    print(f"Network written to {NETWORK_JSON}")

    if not args.no_report:
        print_report(df)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
